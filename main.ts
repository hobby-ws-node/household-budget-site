// Hearth — household budget website entry point
// main.ts: copies app/ and screenshots/ to the output directory and writes
// dossier.json via the vendored make.fun library. vendor/makefun-frontend.ts
// must remain untouched: the competition transcript check requires it.
//
// The site in app/ is a static, browser-open budget tracker (ES modules, CSS,
// no build step). screenshots/ holds up to 4 screenshots of the running site.

import { cpSync, existsSync, mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildDossier } from './vendor/makefun-frontend.ts';

const here = fileURLToPath(new URL('.', import.meta.url));
const out = process.env.MAKEFUN_OUTPUT_DIR ?? '/output';

mkdirSync(out, { recursive: true });
cpSync(join(here, 'app'), join(out, 'app'), { recursive: true });
mkdirSync(join(out, 'screenshots'), { recursive: true });
if (existsSync(join(here, 'screenshots'))) cpSync(join(here, 'screenshots'), join(out, 'screenshots'), { recursive: true });

// The scorer's own caps (reference/gate.json): only text_max_bytes shapes the bytes; the others refuse an entry the
// scorer would refuse (more than 4 screenshots or one over 256 KiB; more than 993 files and directories in app/ or
// 16 MiB of app files: app/ counts beside /output's own 1000-entry cap, its screenshots/ and dossier.json).
// buildDossier produces the judge-read summary: screenshots metadata,
// first-load files/bytes, and your source, all constrained by the caps
// (text_max_bytes, screenshots max count/size, app file/size limits).
writeFileSync(
  join(out, 'dossier.json'),
  buildDossier(out, { text_max_bytes: 163840, screenshots: { max: 4, max_bytes: 262144 }, app_max_files: 993, app_max_bytes: 16777216 }),
);
